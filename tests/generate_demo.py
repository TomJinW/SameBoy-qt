"""Generate an original GB demo ROM: scrolling stripes; A changes the palette."""
import pathlib
import sys

rom = bytearray(32768)
rom[0x100:0x103] = bytes([0xC3, 0x50, 0x01])
rom[0x134:0x143] = b"SAMEBOY QT DEMO"
code = bytearray()
labels = {}
fixups = []


def emit(*values):
    code.extend(values)


def label(name):
    labels[name] = len(code)


def jump(opcode, name):
    emit(opcode, 0)
    fixups.append((len(code) - 1, name))


emit(0xF3, 0xAF, 0xE0, 0x40)  # Disable interrupts and LCD.
emit(0x21, 0x00, 0x80, 0x06, 8)
label("tile")
emit(0x3E, 0xAA, 0x22, 0xAF, 0x22, 0x05)
jump(0x20, "tile")
emit(0x21, 0x00, 0x98, 0x01, 0x00, 0x04)
label("map")
emit(0xAF, 0x22, 0x0B, 0x78, 0xB1)
jump(0x20, "map")
emit(0x3E, 0xE4, 0xE0, 0x47, 0x3E, 0x91, 0xE0, 0x40)
label("frame")
emit(0xF0, 0x44, 0xFE, 144)
jump(0x20, "frame")
emit(0xF0, 0x43, 0x3C, 0xE0, 0x43)
emit(0x3E, 0x10, 0xE0, 0x00, 0xF0, 0x00, 0xE6, 1)
jump(0x28, "pressed")
emit(0x3E, 0xE4)
jump(0x18, "palette")
label("pressed")
emit(0x3E, 0x1B)
label("palette")
emit(0xE0, 0x47)
label("wait")
emit(0xF0, 0x44, 0xFE, 144)
jump(0x28, "wait")
jump(0x18, "frame")
for offset, name in fixups:
    code[offset] = (labels[name] - offset - 1) & 0xFF
rom[0x150:0x150 + len(code)] = code
checksum = 0
for value in rom[0x134:0x14D]:
    checksum = (checksum - value - 1) & 0xFF
rom[0x14D] = checksum
total = sum(rom[:0x14E]) + sum(rom[0x150:])
rom[0x14E:0x150] = (total & 0xFFFF).to_bytes(2, "big")
path = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "demo.gb")
path.write_bytes(rom)
print(path.resolve())
